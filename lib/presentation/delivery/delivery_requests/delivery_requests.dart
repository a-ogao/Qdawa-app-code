class _DeliveryRequestsState extends State<DeliveryRequests> {
  final GlobalKey<ScaffoldState> _scaffoldKey = GlobalKey<ScaffoldState>();

  final TextEditingController searchController = TextEditingController();
  late Future<List<dynamic>> _futureOrders;
  Map<String, dynamic> counters = {
    "quotations": 0,
    "orders": 0,
    "totalAmount": "KSH 0",
    "delivered": 0,
    "notification": 0,
  };

  @override
  void initState() {
    super.initState();
    // ensure UI updates when search text changes
    searchController.addListener(() {
      setState(() {});
    });

    _futureOrders = fetchOrders();
    fetchCounters();
  }

  @override
  void dispose() {
    searchController.removeListener(
        () {}); // safe-remove (listener already removed by GC, but ok)
    searchController.dispose();
    super.dispose();
  }

  Future<void> fetchCounters() async {
    try {
      final SharedPreferences prefs = await SharedPreferences.getInstance();
      final String? userDataString = prefs.getString('userData');

      if (userDataString == null) {
        print("User data is not available");
        return;
      }

      final Map<String, dynamic> userData = json.decode(userDataString);
      final int? userId = userData['id'];

      if (userId == null) {
        print("User ID is not available in userData");
        return;
      }
      final response = await http.post(
        Uri.parse(AppConfig.buildApiUrl('deliverycounters')),
        body: {'usr_id': userId.toString()},
      );
      if (response.statusCode == 200) {
        try {
          final decoded = json.decode(response.body);
          if (decoded is Map<String, dynamic>) {
            setState(() {
              counters = decoded;
            });
          } else {
            print("Unexpected counters payload: ${response.body}");
          }
        } catch (e) {
          print("Error decoding counters JSON: $e");
        }
      } else {
        print("Failed to fetch counters: ${response.statusCode}");
      }
    } catch (e) {
      print("Error fetching counters: $e");
    }
  }

  Future<List<dynamic>> fetchOrders() async {
    try {
      final SharedPreferences prefs = await SharedPreferences.getInstance();
      final String? userDataString = prefs.getString('userData');

      if (userDataString == null) {
        throw Exception("User data is missing.");
      }

      final Map<String, dynamic> userData = json.decode(userDataString);
      final int? userId = userData['id'];

      if (userId == null) {
        throw Exception("User ID is missing.");
      }

      final response = await http.post(
        Uri.parse(AppConfig.buildApiUrl('get_delivery_request')),
        body: {'usr_id': userId.toString()},
      );

      if (response.statusCode != 200) {
        throw Exception(
            "Failed to fetch Request. Status: ${response.statusCode}");
      }

      final data = json.decode(response.body);
      if (data is Map<String, dynamic>) {
        return data['orders'] ?? [];
      } else {
        return [];
      }
    } catch (e) {
      throw Exception("Error fetching Request: $e");
    }
  }

